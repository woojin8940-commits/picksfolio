/**
 * 로고 하나. `size` 는 타일 한 변(px)이다.
 *
 * 아이콘일 뿐이므로 이름을 읽어 주지 않는다(aria-hidden) — 이름은 로고를 감싼
 * 버튼·링크 쪽(글자 또는 aria-label)이 알려 준다.
 */
export const PlatformLogo: React.FC<{
  platform: DefaultButtonKey;
  size?: number;
  className?: string;
}> = ({ platform, size = 16, className = '' }) => {
  const mark = MARKS[platform];
  if (!mark) return null;
  const inner = Math.round(size * mark.scale * 100) / 100;
  return (
    <span
      aria-hidden="true"
      className={`inline-flex items-center justify-center shrink-0 overflow-hidden ${className}`}
      style={{
        width: size,
        height: size,
        borderRadius: Math.max(2, Math.round(size * 0.28)),
        backgroundColor: mark.bg,
      }}
    >
      <svg width={inner} height={inner} viewBox="0 0 24 24" fill={mark.fg} focusable="false">
        <path d={mark.path} />
      </svg>
    </span>
  );
};

export default PlatformLogo;
