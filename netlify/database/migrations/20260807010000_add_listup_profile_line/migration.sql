-- 브랜드 카드에 찍히는 한 줄 소개.
--
-- 추천 카드에는 이름 아래에 "뷰티 · 20대 · 여성" 같은 줄이 들어간다. 이 값을
-- 인플루언서 프로필에서 끌어오지 않고 명단 행에 두는 이유는 두 가지다.
--
-- 하나, 우리는 인플루언서의 나이와 성별을 받지 않는다. 받지 않는 값을 표에만
-- 만들어 두면 영원히 비어 있는 칸이 되고, 화면에는 카테고리만 남는다.
--
-- 둘, 이 줄은 프로필이 아니라 추천의 일부다. 같은 사람이라도 뷰티 캠페인에서는
-- "뷰티 · 20대 · 여성"으로, 홈카페 캠페인에서는 "홈카페 · 자취 브이로그"로 소개하는
-- 것이 맞다. 담당자가 캠페인마다 다르게 적을 수 있어야 한다.
--
-- 비워 두면 화면은 스냅샷의 카테고리로 되돌아간다. 담당자가 매번 적어야만 카드가
-- 완성되는 구조는 만들지 않는다.

