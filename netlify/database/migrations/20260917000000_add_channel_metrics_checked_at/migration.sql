-- 지표를 통째로 마지막으로 물어본 시각.
--
-- creator_channels 의 팔로워·평균 조회수·최근 릴스·최근 피드는 지금까지 두 순간에만
-- 채워졌다 — 계정을 연동할 때, 그리고 인플루언서가 자기 화면에서 '갱신'을 누를 때.
-- 둘 다 인플루언서의 손이 필요한 일이라, 담당자·운영자 대시보드는 연동한 날의
-- 숫자와 그날의 게시물 목록을 지금 것처럼 보여 줬다. 인플루언서가 지운 게시물이
-- 명단에 계속 남고, 팔로워가 두 배가 된 사람도 몇 달 전 숫자로 남는다.
--
-- 그래서 두 곳에서 지표를 다시 받아 온다. 매일 도는 배치가 마지막으로 물어본 지
-- 오래된 계정부터 정해진 수만큼 돌리고, 담당자·운영자가 명부를 여는 길에도 가장
-- 오래된 몇 계정만 뒤에서 다시 받는다. 그 "오래된 순서"를 정하는 값이 이 칸이다.
--
-- synced_at 과 따로 두는 이유. 그 칸은 "지표를 받아 굳힌 시각"이라 성공한 순간만
-- 찍힌다. 그것만으로 순서를 정하면 토큰이 죽었거나 메타가 실패를 돌려준 계정이
-- 영원히 목록 맨 앞에 남아, 뒤에 선 계정들은 한 번도 차례가 오지 않는다. 이 칸은
-- 성공·실패와 무관하게 "물어본 시각"을 찍는다(profile_image_checked_at 과 같은 규칙).

ALTER TABLE creator_channels
  ADD COLUMN IF NOT EXISTS metrics_checked_at TIMESTAMPTZ;

-- 이미 한 번 받아 둔 행은 그때 물어본 것이 맞다. NULL 로 두면 연동만 해 둔 계정과
-- 방금 동기화한 계정이 같은 순서에 서서, 첫 실행이 이미 최신인 행부터 훑는다.
UPDATE creator_channels
   SET metrics_checked_at = synced_at
 WHERE metrics_checked_at IS NULL AND synced_at IS NOT NULL;
