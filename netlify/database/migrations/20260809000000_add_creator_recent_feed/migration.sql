-- 인플루언서 채널의 "최근 피드 9개".
--
-- 리스트업 카드에는 지금까지 최근 릴스 썸네일 3개와 평균 숫자만 실렸다. 그런데
-- 브랜드가 후보를 고를 때 실제로 확인하는 것은 평균 조회수가 아니라 "이 계정의
-- 톤이 우리 브랜드와 맞는가"다. 릴스 3개로는 그 판단이 안 된다 — 릴스는 계정에서
-- 가장 힘을 준 콘텐츠라 평소 피드 분위기와 다르게 생기는 경우가 많다.
--
-- 그래서 릴스와 별개로 일반 피드 미디어를 함께 받아 둔다. 개수를 9로 못 박는
-- 이유는 3×3 한 화면에 들어가야 후보끼리 비교가 되기 때문이다. 더 늘리면 카드가
-- 프로필 페이지처럼 길어져서 명단을 위아래로 훑을 수 없다.
--
-- 릴스(recent_reels)와 컬럼을 나누는 이유는 평균 계산 때문이다. 릴스에만 조회수가
-- 있어서 사진 게시물을 같은 배열에 섞으면 "평균 조회수"가 무슨 숫자인지 알 수
-- 없어진다. 표시용 피드와 계산용 릴스는 처음부터 따로 둔다.
--
-- 저장 모양: [{ id, permalink, thumbnailUrl, mediaType, caption, likes, comments, timestamp }]
-- (thumbnailUrl 은 사진이면 media_url, 영상이면 thumbnail_url 이다. 메타의 미디어
--  URL 은 만료되므로 오래된 값은 깨진 이미지가 될 수 있다 — 화면은 썸네일이 없는
--  칸을 회색 자리로 그려서 "게시물이 없다"와 구분한다.)

ALTER TABLE creator_channels
  ADD COLUMN IF NOT EXISTS recent_feed JSONB DEFAULT '[]'::jsonb;
