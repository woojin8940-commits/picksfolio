-- 연동한 인스타 계정의 고유 아이디(user_id).
--
-- 지금까지 "이 명단 행이 어느 인스타 계정의 것인가"는 instagram_handle(@아이디)로만
-- 알 수 있었다. 그런데 @아이디는 사람이 인스타에서 언제든 바꿀 수 있는 이름이고,
-- 바꿔도 계정 자체(user_id)는 그대로다.
--
-- 그래서 이름만 보고 판단하면 두 가지를 구분할 수 없다.
--   · 같은 사람이 아이디를 바꿨다            → 쌓아 둔 팔로워·평균 조회수는 계속 이 사람 것이다.
--   · 다른 인스타 계정으로 다시 연동했다      → 지난 계정의 숫자를 물려받으면 안 된다.
-- 지금 코드는 이름이 다르면 무조건 뒤쪽으로 보기 때문에, 아이디를 바꾼 인플루언서는
-- 다음 동기화에서 (권한 때문에 이번에 못 받은) 숫자가 0 으로 굳어 버린다.
--
-- user_id 를 함께 굳혀 두면 그 구분이 가능해진다. 옛 행에는 값이 없으므로, 없을 때는
-- 지금까지처럼 이름으로 견주고 다음 동기화에서 값이 채워진다.
ALTER TABLE creator_channels
  ADD COLUMN IF NOT EXISTS instagram_user_id TEXT DEFAULT '';
