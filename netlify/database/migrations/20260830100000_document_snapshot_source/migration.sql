-- 팔로워 스냅샷의 source 값에 'sync' 를 추가로 쓴다는 사실을 표에 적어 둔다.
--
-- 스냅샷 표는 만든 날부터만 쌓이므로, 표를 만든 날 인사이트 화면을 연 인플루언서에게는
-- 점이 하나뿐이고 증감 추이 그래프에 선이 그려지지 않는다. 그런데 그 사람의 과거
-- 팔로워 수는 이미 한 번 관측해 둔 적이 있다 — creator_channels 의 followers 와 그
-- 값을 받아 온 시각(synced_at)이다. 그 쌍을 스냅샷으로 옮기면 만들어 낸 값 없이도
-- 그래프가 첫날부터 무언가를 말할 수 있다.
--
-- 옮긴 줄은 배치('batch')나 본인 화면('live')이 관측한 줄과 구분해야 한다. 같은 날
-- 줄이 이미 있으면 옮기지 않으므로(ON CONFLICT DO NOTHING) 이 값이 더 늦게 관측된
-- 값을 덮는 일은 없다.
--
-- 스키마는 바뀌지 않는다. source 는 원래 자유 문자열이고, 여기서 붙이는 것은 설명뿐이다.
COMMENT ON COLUMN creator_follower_snapshots.source IS
  '관측 경로. batch = 매일 도는 스냅샷 배치, live = 인플루언서가 인사이트 화면을 열어 그 자리에서 받아 온 값, sync = creator_channels 에 이미 저장돼 있던 과거 관측값(synced_at 기준)을 옮긴 줄.';
