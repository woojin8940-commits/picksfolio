-- 캠페인마다 받는 담당자 이름 · 연락처.
--
-- 지금까지 브랜드 담당자 연락처는 계정에 한 벌만 있었다(가입할 때 적은 값).
-- 담당자 화면은 그 값을 읽어 보여 주고 있었지만, 실제 운영에서는 계정 하나에
-- 담당자가 여러 명인 경우가 흔하다.
--
--   · 대행사 계정 하나로 여러 브랜드의 캠페인을 올린다 — 캠페인마다 담당 AE 가 다르다.
--   · 가입한 사람은 이미 퇴사했고, 지금 이 캠페인을 맡은 사람은 다른 사람이다.
--   · 마케팅팀이 올렸지만 제품 발송은 물류 담당자가 답할 수 있다.
--
-- 그래서 계정 정보 대신 "이 캠페인에 대해 물어볼 사람"을 등록할 때마다 받는다.
-- 캠페인 행에 함께 남기므로, 담당자는 캠페인을 열면 그 캠페인의 담당자에게 바로
-- 연락할 수 있고, 계정 정보는 이 칸이 빈 옛 캠페인의 폴백으로만 쓰인다.
--
-- 개인정보다. 캠페인 목록 API 는 공개 조회(인플루언서의 캠페인 탐색)에도 같은 행을
-- 쓰므로, 이 세 칸은 계정 주인이라고 확인된 요청과 픽스폴리오 담당자에게만 응답에
-- 담긴다(api-campaigns 의 stripContact · api-manager-brand-contact 참고).
--
-- 기존 행에는 빈 문자열이 들어간다. 값을 채워 넣지 않는 이유는, 가입 정보를 복사해
-- 두면 "이 캠페인 담당자"와 "가입한 사람"을 구별할 수 없게 되기 때문이다 — 빈 값은
-- 조회 쪽에서 계정 정보로 대체되고, 화면에는 출처가 계정임을 함께 표시한다.
