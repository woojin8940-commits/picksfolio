-- 프로필 사진을 마지막으로 인스타에 물어본 시각.
--
-- creator_channels.profile_image 는 지금까지 두 순간에만 채워졌다 — 계정을 연동할 때,
-- 그리고 인플루언서가 자기 화면에서 '갱신'을 누를 때. 둘 다 인플루언서의 손이 필요한
-- 일이라, 연동해 둔 사람이 인스타에서 프로필 사진을 바꿔도 우리 화면에는 연동한 날의
-- 얼굴이 그대로 남았다. 브랜드는 진행사항 카드에서 지금 인스타에 없는 사진을 보고
-- "이 사람이 맞나"를 의심한다.
--
-- 그래서 브랜드·담당자가 명단을 열 때 사진만 따로 다시 받아 온다. 매번 메타를 부르면
-- 화면이 그만큼 늦어지므로, 계정마다 마지막으로 물어본 시각을 남겨 두고 그 뒤로 몇
-- 시간이 지난 계정만 다시 묻는다.
--
-- 값이 뜻하는 것은 "성공한 시각"이 아니라 "물어본 시각"이다. 토큰이 죽었거나 메타가
-- 실패를 돌려준 경우에도 도장을 찍어야, 실패가 예정된 호출을 페이지를 열 때마다
-- 되풀이하지 않는다. 실패하면 지난 사진은 그대로 남는다.

ALTER TABLE creator_channels
  ADD COLUMN IF NOT EXISTS profile_image_checked_at TIMESTAMPTZ;
